namespace Scout.Cli.Install;

/// <summary>
/// The PreToolUse hook <c>scout install claude</c> writes. It never blocks — it always exits 0 — and it never
/// prints more than <see cref="MaxOutputLines"/> lines (rule 7's hook-output cap), so it stays a cheap nudge
/// rather than something an agent has to read past.
/// </summary>
internal static class ClaudeHookScript
{
    internal const int MaxOutputLines = 3;

    // Kept as an explicit, countable list (rather than a free-form template) so a test can assert the budget
    // directly instead of trusting the generated script's formatting.
    private static readonly string[] OutputLines =
    [
        "Scout kernel available for this project.",
        "Prefer scout_brief/scout_read/scout_neighbors (or `scout query`) over blind grep+read."
    ];

    internal static string Render(string kernelPath)
    {
        if (OutputLines.Length > MaxOutputLines)
        {
            throw new InvalidOperationException("The hook's own output exceeds its line budget.");
        }

        var lines = string.Join("\\n", OutputLines.Select(Escape));
        return $$"""
            #!/usr/bin/env node
            // Generated by `scout install claude`. Informational only: always exits 0, never blocks the tool call,
            // and prints at most {{MaxOutputLines}} lines. Kernel: {{Escape(kernelPath)}}
            process.stdin.resume();
            process.stdin.on('end', () => {
              process.stdout.write("{{lines}}\n");
              process.exit(0);
            });
            """;
    }

    private static string Escape(string value) => value.Replace("\\", "\\\\").Replace("\"", "\\\"");
}
